/* CPU exception entry stubs. Each pushes a uniform frame (see struct
 * interrupt_frame in vexa/arch.h) and jumps to isr_common. */

.macro ISR_NOERR vector
isr_stub_\vector:
    pushq $0
    pushq $\vector
    jmp isr_common
.endm

.macro ISR_ERR vector
isr_stub_\vector:
    pushq $\vector
    jmp isr_common
.endm

.text
isr_common:
    pushq %rax
    pushq %rbx
    pushq %rcx
    pushq %rdx
    pushq %rsi
    pushq %rdi
    pushq %rbp
    pushq %r8
    pushq %r9
    pushq %r10
    pushq %r11
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15
    cld
    movq %rsp, %rdi
    /* Align the stack to 16 bytes for the C ABI, keeping the old rsp. */
    movq %rsp, %rbx
    andq $-16, %rsp
    call interrupt_dispatch
    movq %rbx, %rsp
    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %r11
    popq %r10
    popq %r9
    popq %r8
    popq %rbp
    popq %rdi
    popq %rsi
    popq %rdx
    popq %rcx
    popq %rbx
    popq %rax
    addq $16, %rsp /* Drop vector and error code. */
    iretq

